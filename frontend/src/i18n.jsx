const LanguageContext = createContext(null);

function getInitialLanguage() {
  try {
    return localStorage.getItem(LANGUAGE_KEY) === "ja" ? "ja" : "ko";
  } catch {
    return "ko";
  }
}

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(getInitialLanguage);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const changeLanguage = useCallback((nextLanguage) => {
    if (nextLanguage !== "ko" && nextLanguage !== "ja") return;
    setLang(nextLanguage);
    try {
      localStorage.setItem(LANGUAGE_KEY, nextLanguage);
    } catch {
      // The selected language still applies for the current page.
    }
  }, []);

  const t = useCallback((key, values = {}) => {
    const translated = lang === "ja" ? ja[key] ?? key : key;
    return translated.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? "");
  }, [lang]);

  const contextValue = useMemo(
    () => ({ lang, setLanguage: changeLanguage, t }),
    [lang, changeLanguage, t],
  );

  return (
    <LanguageContext.Provider value={contextValue}>
      {children}
    </LanguageContext.Provider>
  );
}

// eslint-disable-next-line react-refresh/only-export-components
export function useI18n() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useI18n must be used within LanguageProvider");
  return context;
}
